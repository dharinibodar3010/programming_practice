
public class StudentModel {
    private int id;
    private String sname, ssurname, stream, city, edu, percentage, ptech, gender;
    private int fees;

    // Getters and Setters for all fields
    public int getId() { return id; }
    public void setId(int id) { this.id = id; }
    
    public String getSname() { return sname; }
    public void setSname(String sname) { this.sname = sname; }
    
    public String getSsurname() { return ssurname; }
    public void setSsurname(String ssurname) { this.ssurname = ssurname; }
    
    public String getStream() { return stream; }
    public void setStream(String stream) { this.stream = stream; }
    
    public String getCity() { return city; }
    public void setCity(String city) { this.city = city; }
    
    public String getEdu() { return edu; }
    public void setEdu(String edu) { this.edu = edu; }
    
    public String getPercentage() { return percentage; }
    public void setPercentage(String percentage) { this.percentage = percentage; }
    
    public String getPtech() { return ptech; }
    public void setPtech(String ptech) { this.ptech = ptech; }
    
    public String getGender() { return gender; }
    public void setGender(String gender) { this.gender = gender; }
    
    public int getFees() { return fees; }
    public void setFees(int fees) { this.fees = fees; }
}
	